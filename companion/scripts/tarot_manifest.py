def prompt_for(card: TarotCard) -> str:
    if card.path.startswith("major/"):
        style = STYLE_MAJOR
    elif card.path.startswith("wands/"):
        style = STYLE_WANDS
    elif card.path.startswith("cups/"):
        style = STYLE_CUPS
    elif card.path.startswith("swords/"):
        style = STYLE_SWORDS
    elif card.path.startswith("coins/"):
        style = STYLE_COINS
    elif card.path == "back.png":
        style = STYLE_BACK
    elif card.path == "blank.png":
        style = STYLE_BLANK
    else:
        style = STYLE_MAJOR
    return f"{style}。{card.palette}。{card.scene}"


