def of(card_id: str) -> Lore | None:
    return LORE.get(card_id or "")


def angle(card_id: str, reversed: bool) -> str:
    row = of(card_id)
    if not row:
        return ""
    scene, up, rev = row
    face = rev if reversed else up
    other = up if reversed else ""
    lines = [f"画面：{scene}", f"这面：{face}"]
    if reversed and other:
        lines.append(f"正位是「{other}」。这张倒过来，还是同一张牌。")
    return "\n   ".join(lines)
